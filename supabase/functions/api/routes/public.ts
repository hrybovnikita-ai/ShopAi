interface CatalogProduct extends ProductRow {
  price: number;
  rating: number;
  stock: number;
  image_url: string;
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export async function handleHealth(): Promise<Response> {
  const started = performance.now();
  let database = { ok: true, latencyMs: 0, error: null as string | null };

  try {
    await dbSelect("products", { select: "id", limit: "1" });
    database.latencyMs = Math.round(performance.now() - started);
  } catch (error) {
    database = {
      ok: false,
      latencyMs: Math.round(performance.now() - started),
      error: error instanceof HttpError ? error.message : "Database check failed",
    };
  }

  return json({
    status: database.ok ? "ok" : "degraded",
    service: "shopai-api",
    environment: env.environment,
    uptimeSeconds: Math.floor((Date.now() - STARTED_AT) / 1000),
    timestamp: new Date().toISOString(),
    database,
    ai: { configured: Boolean(env.openaiKey), embeddings: embeddingSource() },
  }, database.ok ? 200 : 503);
}

function parsePriceLimit(query: string): number | null {
  const patterns = [
    /(?:under|below|less than|up to|max(?:imum)?(?: of)?|budget(?: of)?|cheaper than)\s*\$?\s*(\d+(?:[.,]\d+)?)/i,
    /\$\s*(\d+(?:[.,]\d+)?)/,
    /(\d+(?:[.,]\d+)?)\s*(?:dollars|usd)/i,
  ];
  for (const pattern of patterns) {
    const match = query.match(pattern);
    if (match) {
      const value = Number(match[1].replace(",", "."));
      if (Number.isFinite(value) && value > 0) return value;
    }
  }
  return null;
}

function detectCategory(query: string, categories: string[]): string | null {
  const lower = query.toLowerCase();
  return categories.find((category) => lower.includes(category.toLowerCase())) ?? null;
}

function lexicalScore(product: CatalogProduct, tokens: string[]): number {
  if (tokens.length === 0) return 0;
  const name = product.name.toLowerCase();
  const rest = `${product.category} ${product.description} ${(product.features ?? []).join(" ")}`.toLowerCase();
  let hits = 0;
  for (const token of tokens) {
    if (name.includes(token)) hits += 2;
    else if (rest.includes(token)) hits += 1;
  }
  return Math.min(1, hits / (tokens.length * 2));
}

export async function handleSemanticSearch({ req }: RouteContext): Promise<Response> {
  const body = await readJson<{ query?: string; limit?: number }>(req);
  const query = (body.query ?? "").trim();
  if (!query) throw new HttpError(400, "Describe what you are looking for", "invalid_query");
  if (query.length > 300) throw new HttpError(400, "Keep the search under 300 characters", "invalid_query");
  const limit = Math.max(1, Math.min(Number(body.limit) || 8, 12));

  await ensureProductEmbeddings();

  const { data: products } = await dbSelect<CatalogProduct[]>("products", {
    select: "*",
    is_active: "eq.true",
  });
  const { data: categories } = await dbSelect<{ name: string }[]>("categories", { select: "name" });

  let similarities = new Map<string, number>();
  let embeddingMode: "ai-embeddings" | "local-embeddings";
  let notice: string;

  try {
    const { literal, source } = await embedQuery(query);
    const matches = await dbRpc<{ product_id: string; similarity: number }[]>("match_products", {
      query_embedding: literal,
      match_count: Math.max(24, products.length),
    });
    similarities = new Map(matches.map((row) => [row.product_id, row.similarity]));
    embeddingMode = source === LOCAL_SOURCE ? "local-embeddings" : "ai-embeddings";
    notice = source === LOCAL_SOURCE
      ? "Ranked with local embeddings stored in PostgreSQL (pgvector). Configure an AI provider for model embeddings."
      : "Ranked with embeddings generated by the configured AI provider and stored in PostgreSQL (pgvector).";
  } catch (error) {
    embeddingMode = "local-embeddings";
    notice = "Vector ranking is unavailable right now; results use keyword matching over the stored catalog.";
    logLine("warn", "Semantic search fell back to keyword matching", {
      reason: error instanceof Error ? error.message : "unknown",
    });
  }

  const maxPrice = parsePriceLimit(query);
  const category = detectCategory(query, categories.map((row) => row.name));
  const tokens = keywords(query);

  const scored = products
    // Budget is a hard constraint; the category only boosts matching products
    // so a "gaming laptop" query can still surface a closely related item.
    .filter((product) => (maxPrice == null || product.price <= maxPrice))
    .map((product) => {
      const similarity = Math.max(0, similarities.get(product.id) ?? 0);
      const lexical = lexicalScore(product, tokens);
      const categoryBoost = category && product.category.toLowerCase() === category.toLowerCase() ? 1 : 0;
      const score = Math.round((similarity * 0.62 + lexical * 0.28 + categoryBoost * 0.1) * 1000) / 1000;
      const matchedKeywords = tokens.filter((token) =>
        `${product.name} ${product.category} ${product.description} ${(product.features ?? []).join(" ")}`
          .toLowerCase()
          .includes(token)
      ).slice(0, 6);
      return { ...product, similarity: Math.round(similarity * 1000) / 1000, lexicalScore: lexical, score, matchedKeywords };
    })
    .sort((a, b) => b.score - a.score || b.rating - a.rating);

  const hasSignals = tokens.length > 0 || maxPrice != null || category != null;

  // Keep only products with a real signal (keyword, category or strong vector
  // similarity) so a budgeted search never pads results with unrelated items.
  const relevant = scored.filter((product) => {
    const categoryMatch = category && product.category.toLowerCase() === category.toLowerCase();
    return (product.matchedKeywords?.length ?? 0) > 0 || Boolean(categoryMatch) || product.similarity >= 0.2;
  });

  const ranked = hasSignals ? (relevant.length > 0 ? relevant : []) : [...products].sort((a, b) => b.rating - a.rating);
  const results = ranked.slice(0, limit).map((product) => {
    const reasonParts: string[] = [];
    if (product.matchedKeywords?.length) {
      reasonParts.push(`matches ${product.matchedKeywords.slice(0, 3).map((keyword) => `“${keyword}”`).join(", ")}`);
    }
    if (maxPrice != null) reasonParts.push(`within $${maxPrice.toFixed(0)}`);
    if (category && product.category.toLowerCase() === category.toLowerCase()) reasonParts.push(`${category} category`);
    if (reasonParts.length === 0) reasonParts.push("top rated in the catalog");
    return {
      ...product,
      reason: `${reasonParts.join(" · ")} (${Math.round((product.similarity ?? 0) * 100)}% vector similarity)`,
    };
  });

  return json({
    query,
    mode: embeddingMode,
    notice,
    interpreted: { maxPrice, category, keywords: tokens.slice(0, 8) },
    total: results.length,
    results,
    suggestions: hasSignals && results.length === 0
      ? [...products].sort((a, b) => b.rating - a.rating).slice(0, 3)
      : [],
  });
}

export async function handleCompare({ req }: RouteContext): Promise<Response> {
  const body = await readJson<{ productIds?: string[]; requirements?: string }>(req);
  const ids = Array.isArray(body.productIds) ? [...new Set(body.productIds)] : [];

  if (ids.length < 2 || ids.length > 4) {
    throw new HttpError(400, "Select between 2 and 4 products to compare", "invalid_selection");
  }
  if (!ids.every((id) => typeof id === "string" && UUID_RE.test(id))) {
    throw new HttpError(400, "One or more product ids are invalid", "invalid_selection");
  }

  const { data } = await dbSelect<CompareProduct[]>("products", {
    select: "id,name,description,price,rating,category,stock,features,image_url",
    id: `in.(${ids.join(",")})`,
  });

  if (data.length < 2) throw new HttpError(404, "Those products are no longer available", "products_not_found");

  const ordered = ids
    .map((id) => data.find((product) => product.id === id))
    .filter((product): product is CompareProduct => Boolean(product));

  const result = await compareProducts(ordered, (body.requirements ?? "").slice(0, 500));
  return json(result);
}

export async function handleCreateOrder({ req }: RouteContext): Promise<Response> {
  const body = await readJson<{
    customer_name?: string;
    customer_email?: string;
    items?: { product_id?: string; quantity?: number }[];
    shipping_address?: Record<string, unknown>;
  }>(req);

  const customerName = (body.customer_name ?? "").trim();
  const customerEmail = (body.customer_email ?? "").trim();
  const items = Array.isArray(body.items) ? body.items : [];

  if (customerName.length < 2) throw new HttpError(400, "Enter the customer name", "invalid_order");
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(customerEmail)) {
    throw new HttpError(400, "Enter a valid email address", "invalid_order");
  }
  if (items.length === 0) throw new HttpError(400, "Your cart is empty", "invalid_order");
  if (items.some((item) => !item.product_id || !UUID_RE.test(item.product_id) || !Number.isInteger(item.quantity) || (item.quantity ?? 0) < 1)) {
    throw new HttpError(400, "One or more cart items are invalid", "invalid_order");
  }

  const user = await getAuthUser(req);

  const order = await dbRpc<{ id: string; total: number; tax: number; item_count: number; status: string }>("create_order", {
    payload: {
      customer_name: customerName,
      customer_email: customerEmail,
      items: items.map((item) => ({ product_id: item.product_id, quantity: item.quantity })),
      shipping_address: body.shipping_address ?? {},
    },
    p_user_id: user?.id ?? null,
  });

  return json({
    order: {
      ...order,
      number: order.id.slice(0, 8).toUpperCase(),
    },
  }, 201);
}
